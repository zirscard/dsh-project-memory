/**
 * Host-half tests for dsh-project-memory.
 *
 * Mocks the parts of the cordis context the plugin uses, then drives the real
 * tool against the real Python engine — so this exercises the whole chain:
 * tool → runner → core/memory.py → files on disk → dynamic prompt section.
 *
 * Run:  ELECTRON_RUN_AS_NODE=1 "<electron>" test/run_host_tests.mjs
 * Exit 0 = all passed.
 */
import { mkdtemp, rm } from 'node:fs/promises'
import { existsSync, readFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import assert from 'node:assert/strict'

const HERE = dirname(fileURLToPath(import.meta.url))
const { apply } = await import(join(HERE, '..', 'index.js'))

const passed = []
const failed = []

function check(name, fn) {
  try {
    fn()
    passed.push(name)
    console.log(`  ✓ ${name}`)
  } catch (error) {
    failed.push(`${name} :: ${error.message}`)
    console.log(`  ✗ ${name} :: ${error.message}`)
  }
}

async function checkAsync(name, fn) {
  try {
    await fn()
    passed.push(name)
    console.log(`  ✓ ${name}`)
  } catch (error) {
    failed.push(`${name} :: ${error.message}`)
    console.log(`  ✗ ${name} :: ${error.message}`)
  }
}

/* ---- mock cordis context ------------------------------------------- */
const tools = []
const sections = []
const ctx = {
  tools: {
    register(tool) {
      tools.push(tool)
      return () => { /* disposer */ }
    },
  },
  systemPrompt: {
    section(options) {
      sections.push(options)
      return () => { /* disposer */ }
    },
  },
  effect(fn) {
    // Effects are only used for disposers here; run them so nothing leaks.
    fn()
  },
}

const workspace = await mkdtemp(join(tmpdir(), 'dsh-pm-host-'))
// 隔离：记忆根与 DSH home 都指向临时目录，绝不污染真实的 ~/.dsh/memory
const memHome = join(workspace, 'memory')
process.env.DSH_MEMORY_HOME = memHome
process.env.DSH_HOME = join(workspace, 'dsh-home')
const exec = { agent: { session: { header: { cwd: workspace } } } }

console.log('\n[1] plugin registers')
apply(ctx)
check('注册了 1 个工具', () => assert.equal(tools.length, 1))
check('工具名为 project_memory', () => assert.equal(tools[0].name, 'project_memory'))
check('注册了 1 个 system prompt 段落', () => assert.equal(sections.length, 1))
check('段落名唯一', () => assert.equal(sections[0].name, 'dsh-project-memory'))
check('段落不插值（防 {{}} 抛错）', () => assert.equal(sections[0].interpolate, false))
check('段落正文为函数（每次组装现算）', () => assert.equal(typeof sections[0].text, 'function'))

console.log('\n[2] 初始段落含纪律、不含 core')
const initialText = sections[0].text({})
check('含纪律关键词 source', () => assert.ok(initialText.includes('无源不写')))
check('含 asOf 纪律', () => assert.ok(initialText.includes('asOf')))

console.log('\n[3] write 工具')
const writeResult = await tools[0].execute({
  action: 'write',
  type: 'decision',
  title: 'M1 底稿数字一律保留原始单位并在注释中标注换算',
  body: '诺德基金报表为人民币元，估值底稿为万元；跨表引用必须写明单位换算关系。',
  asOf: '2026-10-20',
  source: '<materials-root>/估值底稿【2026-1】.xlsx#Sheet1',
  scope: 'M1',
  tags: '单位,口径',
  confidence: 0.9,
}, exec)
check('write 成功', () => assert.equal(writeResult.ok, true, JSON.stringify(writeResult).slice(0, 200)))
check('返回条目 ID', () => assert.match(writeResult.id, /^MEM-\d{8}-\d{4}$/))
const entryId = writeResult.id

console.log('\n[4] 参数校验（工具层）')
const missing = await tools[0].execute({ action: 'write', type: 'fact', title: 'x' }, exec)
check('缺 asOf/source 被工具层拒绝', () => assert.equal(missing.ok, false))
check('错误提示点名缺失字段', () => assert.ok(missing.error.includes('asOf') && missing.error.includes('source')))
const noWorkspace = await tools[0].execute({ action: 'status' }, { agent: { session: { header: {} } } })
check('无工作区时给出结构化错误', () => assert.equal(noWorkspace.ok, false))

console.log('\n[5] recall + promote + 动态注入')
const recallResult = await tools[0].execute({ action: 'recall', query: '单位 口径 底稿' }, exec)
check('recall 成功', () => assert.equal(recallResult.ok, true))
check('recall 命中条目', () => assert.ok(recallResult.results.some((r) => r.id === entryId)))

await tools[0].execute({ action: 'promote', id: entryId }, exec)
const afterText = sections[0].text({})
check('段落正文变为函数（动态重算）', () => assert.equal(typeof sections[0].text, 'function'))
check('动态注入含核心记忆 ID', () => assert.ok(afterText.includes(entryId), afterText.slice(-300)))
check('动态注入含核心记忆正文', () => assert.ok(afterText.includes('保留原始单位')))
check('动态注入仍保留纪律', () => assert.ok(afterText.includes('无源不写')))
check('注入内容不含派生物标记（注释已被中和）', () => assert.ok(!afterText.includes('generated by dsh-project-memory')))
// 指针只存路径，不存内容副本
const pointerFile = join(memHome, '.active.json')
check('指针文件存在', () => assert.ok(existsSync(pointerFile), pointerFile))
const pointer = JSON.parse(readFileSync(pointerFile, 'utf8'))
check('指针只含路径不含内容', () => assert.ok(
  typeof pointer.core_path === 'string' && !('core' in pointer),
  JSON.stringify(Object.keys(pointer)),
))

console.log('\n[6] PIT 过滤（工具层，双时间轴）')
await tools[0].execute({
  action: 'write',
  type: 'metric',
  title: '2026 年 7 月起管理费改按季度计提',
  body: '7 月起口径变化，影响收入确认。',
  asOf: '2026-07-01',
  source: '<materials-root>/预算执行情况0709.xlsx#B4',
}, exec)
const pitRecall = await tools[0].execute({ action: 'recall', query: '管理费 计提', asOf: '2026-06-30' }, exec)
check('事件轴过滤排除未来记忆', () => assert.ok(
  !pitRecall.results.some((r) => r.title.includes('管理费')),
  JSON.stringify(pitRecall.results.map((r) => r.title)),
))
check('单轴时给出双轴提示', () => assert.ok((pitRecall.pit_note || '').includes('known-at')))
// 事件轴早于查询时点、但今天才观测到 → 摄入轴必须排除（真正的未来数据泄漏）
await tools[0].execute({
  action: 'write',
  type: 'fact',
  title: '注册资本三亿元的历史沿革',
  body: '2012 年股东会决议修改章程。',
  asOf: '2026-01-01',
  source: '<materials-root>/审计报告附注.docx',
}, exec)
const singleAxis = await tools[0].execute({ action: 'recall', query: '注册资本', asOf: '2026-06-30' }, exec)
check('单事件轴时该记忆可见', () => assert.ok(singleAxis.results.some((r) => r.title.includes('注册资本'))))
const dualAxis = await tools[0].execute({ action: 'recall', query: '注册资本', asOf: '2026-06-30', knownAt: '2026-06-30' }, exec)
check('双轴过滤排除当时未知的记忆', () => assert.ok(
  !dualAxis.results.some((r) => r.title.includes('注册资本')),
  JSON.stringify(dualAxis.results.map((r) => r.title)),
))

console.log('\n[7] leak-check（双时间轴）')
const leak = await tools[0].execute({ action: 'leak-check', asOf: '2026-06-30' }, exec)
check('leak-check 成功', () => assert.equal(leak.ok, true))
check('事件轴检出泄漏候选', () => assert.ok(leak.event_leak_count >= 1))
check('未给 knownAt 时给出摄入轴提示', () => assert.ok((leak.hint || '').includes('known-at')))
const leakDual = await tools[0].execute({ action: 'leak-check', asOf: '2026-06-30', knownAt: '2026-06-30' }, exec)
check('双轴审计给出摄入轴结果', () => assert.ok(Array.isArray(leakDual.knowledge_axis_leaks)))
check('双轴审计不再提示补 known-at', () => assert.ok(!(leakDual.hint || '').includes('known-at')))

console.log('\n[7b] doctor：扩散度审计（工具层）')
const doctor = await tools[0].execute({ action: 'doctor', scope: 'files' }, exec)
check('doctor 成功', () => assert.equal(doctor.ok, true))
check('doctor 判定 CLEAN', () => assert.equal(doctor.verdict, 'CLEAN', JSON.stringify(doctor.metrics)))
check('无工作区遗留目录', () => assert.equal(doctor.metrics.stray_workspace_dirs, 0))
check('无同内容多份副本', () => assert.equal(doctor.metrics.duplicate_content_groups, 0))

console.log('\n[8] 渲染')
const rendered = tools[0].output.render({ action: 'recall' }, recallResult)
check('渲染为文本块', () => assert.ok(Array.isArray(rendered) && rendered[0].type === 'text'))
check('渲染含命中标题', () => assert.ok(rendered[0].text.includes('原始单位')))

await rm(workspace, { recursive: true, force: true })

console.log('\n' + '='.repeat(56))
console.log(`通过 ${passed.length} 项，失败 ${failed.length} 项`)
if (failed.length > 0) {
  for (const f of failed) console.log('  ✗', f)
  process.exit(1)
}
console.log('ALL HOST TESTS PASSED')
process.exit(0)
